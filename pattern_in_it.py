def get_player_boost(player_name, gender):
    if gender == "men":
        return MEN_TOP_25.get(player_name)
    elif gender == "women":
        return WOMEN_TOP_25.get(player_name)
    return None

def check_pattern(match_data):
    """
    Вход: match_data — словарь с данными матча.
    Пример:
    {
      "player1": "Кори Гауфф",
      "player2": "Арина Соболенко",
      "gender": "women",
      "set_results": [4, 6],          # кто сколько геймов взял в 1-м сете
      "p1_double_faults_set1": 2,     # двойные ошибки игрока 1 в 1-м сете
      "p2_double_faults_set1": 1,     # двойные ошибки игрока 2 в 1-м сете
      "total_points_set1": 20        # общее количество разыгранных очков в 1-м сете (опционально)
    }
    Выход: прогноз в формате dict или None, если паттерн не сработал.
    """
    p1 = match_data["player1"]
    p2 = match_data["player2"]
    gender = match_data["gender"]
    s1_p1 = match_data["set_results"][0]
    s1_p2 = match_data["set_results"][1]

    # Кто проиграл первый сет
    loser = p1 if s1_p1 < s1_p2 else p2
    winner = p1 if s1_p1 > s1_p2 else p2

    boost_percent = get_player_boost(loser, gender)
    if boost_percent is None:
        return None  # игрок не в топ-25 — паттерн не срабатывает

    # Сколько двойных было в 1-м сете у проигравшего
    loser_df_set1 = match_data.get("p1_double_faults_set1") if loser == p1 else match_data.get("p2_double_faults_set1")
    if loser_df_set1 is None:
        return None

    # Прогноз: ожидаемое количество двойных во 2-м сете с учётом роста на boost_percent%
    expected_df_set2 = loser_df_set1 * (1 + boost_percent / 100.0)

    forecast_text = (
        f"{loser} проиграл первый сет {s1_p1}-{s1_p2}. "
        f"Прогноз на 2-й сет: количество двойных ошибок ожидается больше {expected_df_set2:.1f} "
        f"(рост на {boost_percent}% по статистике топ-игроков)."
    )

    return {
        "trigger": "pattern_in_it",
        "match": f"{p1} vs {p2}",
        "loser": loser,
        "boost_percent": boost_percent,
        "expected_df_set2": expected_df_set2,
        "forecast_text": forecast_text,
    }
